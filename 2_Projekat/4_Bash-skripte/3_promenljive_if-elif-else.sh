# ----------------------------------------------------------------------------------------------------
# Bash                    # Python

# ----------------------------------------------------------------------------------------------------
# Promenljiva

x=3                       # x = 3

# ----------------------------------------------------------------------------------------------------
# if-else

if (( 5 == "$x" )); then  # if (5 == x):
	echo "5 == $x"        #     print(f"5 == {x}")
else                      # else:
	echo "5 != $x"        #     print(f"5 != {x}")
fi

# ----------------------------------------------------------------------------------------------------
# if-elif-else

if (( 5 > "$x" )); then   # if (5 > x):
	echo "5 > $x"         #     print(f"5 > {x}")
elif (( 5 < "$x" )); then # elif (5 < x):
	echo "5 < $x"         #     print(f"5 < {x}")
else                      # else:
	echo "5 == $x"        #     print(f"5 == {x}")
fi

